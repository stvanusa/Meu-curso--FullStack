//Escreva um programa que imprima os numeros de 10 a 1 usando um loop while
// Inicializa a variável com o valor 10

let numero = 10;
// Loop while que executa enquanto o número for maior ou igual a 1
while (numero >= 1) {
    console.log(numero); // Imprime o número atual
    numero--; // Decrementa o número
}